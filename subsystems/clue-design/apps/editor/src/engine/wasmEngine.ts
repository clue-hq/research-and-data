import type {
  AssetId,
  AssetRecord,
  Diagnostic,
  DocumentMeta,
  ExportProfile,
  Node,
  NodeId,
  Operation,
  Page,
  PageId,
  Scene,
  Slot,
  SlotId
} from "./contracts";
import type { StructuredEdit } from "./structuredEdits";

/**
 * Track E (browser WASM core): the optimistic editing engine.
 *
 * The WASM module owns the local scene in its memory; this wrapper sends
 * operations and structured edits in and receives results, diagnostics, and
 * mechanical scene deltas out. Full scene snapshots cross the boundary only
 * on init, reconcile, and undo frames — never per keystroke. The render
 * snapshot consumed by React is maintained immutably by merging engine
 * deltas (structural sharing), so unchanged entities keep referential
 * identity.
 *
 * Text honesty (Decision E3): the in-browser engine measures text with the
 * lumen-core heuristic fallback because skia-safe cannot target wasm32.
 * Server-computed geometry stays authoritative for text-dependent layout;
 * the editor renders server geometry when available.
 */

/** Raw wasm-bindgen instance surface generated by wasm-pack. */
export interface WasmEngineInstance {
  loadScene(sceneJson: string): void;
  sceneJson(): string;
  applyOperations(operationsJson: string): string;
  applyStructuredEdit(editJson: string): string;
  compileDslBlock(source: string): string;
  layoutGeometry(): string;
  preflight(): string;
  validate(): string;
  version(): string;
  free?(): void;
}

/** Raw wasm-pack module surface (subset the editor uses). */
export interface WasmModule {
  engineVersion(): string;
  slotIdForKey(key: string): string;
  LumenEngine: new (sceneJson: string) => WasmEngineInstance;
}

export interface EngineVersionInfo {
  schema_version: number;
  engine_commit: string;
  text_measurement: string;
}

/**
 * Mechanical scene delta emitted by the engine: per-entity replacements
 * computed by pure before/after comparison in Rust. `null` removes an
 * entry; `export_profiles` replaces the whole array when it changed.
 */
export interface SceneDelta {
  meta?: DocumentMeta;
  pages?: Record<PageId, Page | null>;
  nodes?: Record<NodeId, Node | null>;
  slots?: Record<SlotId, Slot | null>;
  assets?: Record<AssetId, AssetRecord | null>;
  export_profiles?: ExportProfile[];
}

export interface EngineApplyOutcome {
  accepted: boolean;
  scene: Scene;
  message?: string;
  code?: string;
  diagnostics: Diagnostic[];
  inverseOperations: Operation[] | null;
  appliedOperations: number;
}

export interface EngineEditMetadata {
  kind: string;
  touched_targets: unknown[];
  intent: string | null;
  checkpoint_label: string | null;
  inverse_operations: Operation[] | null;
  lineage: unknown | null;
}

export interface EngineStructuredEditOutcome extends EngineApplyOutcome {
  operations: Operation[];
  edit: EngineEditMetadata | null;
}

/**
 * The optimistic engine port EditorApp consumes. `WasmEngine` is the only
 * production implementation since W4 retired the legacy local TS adapter;
 * tests may inject fakes (the `local` kind is reserved for those — local
 * fakes are never enqueued to the server).
 */
export interface OptimisticEnginePort {
  readonly kind: "wasm" | "local";
  readonly scene: Scene;
  readonly version: EngineVersionInfo | null;
  /** Replace local state (reconcile and undo/redo frames). */
  reset(scene: Scene): void;
  applyOperations(operations: Operation[]): EngineApplyOutcome;
  applyStructuredEdit?(edit: StructuredEdit): EngineStructuredEditOutcome;
}

/** Immutable, structurally shared merge of an engine delta into a scene. */
export function applySceneDelta(scene: Scene, delta: SceneDelta): Scene {
  const next: Scene = { ...scene };
  if (delta.meta) {
    next.meta = delta.meta;
  }
  if (delta.pages) {
    next.pages = mergeEntityMap(scene.pages, delta.pages);
  }
  if (delta.nodes) {
    next.nodes = mergeEntityMap(scene.nodes, delta.nodes);
  }
  if (delta.slots) {
    next.slots = mergeEntityMap(scene.slots, delta.slots);
  }
  if (delta.assets) {
    next.assets = mergeEntityMap(scene.assets ?? {}, delta.assets);
  }
  if (delta.export_profiles) {
    next.export_profiles = delta.export_profiles;
  }
  return next;
}

function mergeEntityMap<T>(
  current: Record<string, T>,
  changes: Record<string, T | null>
): Record<string, T> {
  const next: Record<string, T> = { ...current };
  for (const [key, value] of Object.entries(changes)) {
    if (value === null) {
      delete next[key];
    } else {
      next[key] = value;
    }
  }
  return next;
}

export class WasmEngine implements OptimisticEnginePort {
  readonly kind = "wasm" as const;
  readonly version: EngineVersionInfo;
  private readonly instance: WasmEngineInstance;
  private snapshot: Scene;

  constructor(module: WasmModule, initialScene: Scene) {
    this.instance = new module.LumenEngine(JSON.stringify(initialScene));
    this.snapshot = initialScene;
    this.version = JSON.parse(module.engineVersion()) as EngineVersionInfo;
  }

  get scene(): Scene {
    return this.snapshot;
  }

  reset(scene: Scene): void {
    this.instance.loadScene(JSON.stringify(scene));
    this.snapshot = scene;
  }

  /**
   * Full snapshot straight from engine memory. Reserved for reconcile
   * checks and debugging; the editing path consumes deltas only.
   */
  sceneJson(): string {
    return this.instance.sceneJson();
  }

  applyOperations(operations: Operation[]): EngineApplyOutcome {
    const result = JSON.parse(this.instance.applyOperations(JSON.stringify(operations))) as {
      ok: boolean;
      applied_operations?: number;
      diagnostics?: Diagnostic[];
      inverse_operations?: Operation[] | null;
      delta?: SceneDelta;
      error?: { code: string; message: string };
    };
    if (!result.ok) {
      return {
        accepted: false,
        scene: this.snapshot,
        message: result.error?.message ?? "operation batch rejected by the engine",
        code: result.error?.code,
        diagnostics: result.diagnostics ?? [],
        inverseOperations: null,
        appliedOperations: 0
      };
    }
    this.snapshot = applySceneDelta(this.snapshot, result.delta ?? {});
    return {
      accepted: true,
      scene: this.snapshot,
      diagnostics: result.diagnostics ?? [],
      inverseOperations: result.inverse_operations ?? null,
      appliedOperations: result.applied_operations ?? 0
    };
  }

  applyStructuredEdit(edit: StructuredEdit): EngineStructuredEditOutcome {
    const result = JSON.parse(this.instance.applyStructuredEdit(JSON.stringify(edit))) as {
      ok: boolean;
      applied_operations?: number;
      diagnostics?: Diagnostic[];
      operations?: Operation[];
      edit?: EngineEditMetadata;
      delta?: SceneDelta;
      error?: { code: string; message: string };
    };
    if (!result.ok) {
      return {
        accepted: false,
        scene: this.snapshot,
        message: result.error?.message ?? "structured edit rejected by the engine",
        code: result.error?.code,
        diagnostics: result.diagnostics ?? [],
        inverseOperations: null,
        appliedOperations: 0,
        operations: [],
        edit: null
      };
    }
    this.snapshot = applySceneDelta(this.snapshot, result.delta ?? {});
    return {
      accepted: true,
      scene: this.snapshot,
      diagnostics: result.diagnostics ?? [],
      inverseOperations: result.edit?.inverse_operations ?? null,
      appliedOperations: result.applied_operations ?? 0,
      operations: result.operations ?? [],
      edit: result.edit ?? null
    };
  }
}

export function wasmCoreFlagEnabled(): boolean {
  const flag = process.env.NEXT_PUBLIC_LUMEN_WASM_CORE;
  return flag === "1" || flag === "true";
}

export interface WasmModuleLoadOptions {
  /** Base URL the wasm-pack artifacts are served from. */
  baseUrl?: string;
}

/**
 * Runtime loader for the wasm-pack output in `public/wasm/`. The Next.js
 * build never depends on the artifact existing: a missing or failing
 * module resolves to `null` and the editor degrades to server-only mode.
 */
export async function loadWasmModule(
  options: WasmModuleLoadOptions = {}
): Promise<WasmModule | null> {
  const baseUrl = options.baseUrl ?? "/wasm";
  try {
    const moduleUrl = `${baseUrl}/lumen_wasm.js`;
    const module = (await import(/* webpackIgnore: true */ moduleUrl)) as WasmModule & {
      default: (input?: unknown) => Promise<unknown>;
    };
    await module.default({ module_or_path: `${baseUrl}/lumen_wasm_bg.wasm` });
    return module;
  } catch {
    return null;
  }
}

