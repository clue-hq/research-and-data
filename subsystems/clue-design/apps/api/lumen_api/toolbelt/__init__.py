"""The design subsystem's governed write path (Part II slice D6).

**Deliberately light.** Importing this package pulls ``clue_toolbelt`` + pydantic and nothing
else — no FastAPI, no ``clue_design`` DAL, no node toolchain. That is load-bearing: the platform
composition root (``clue_api.design_tools``) imports it to register the design tool *envelopes*
in the platform tool registry, so the C6 authority audit remains a complete, static statement
about every durable write the platform can name, and enabling ``design_runtime_enabled`` can
never change the registry's shape. Every heavy design collaborator is imported inside a function
body (see ``base.DesignToolHost``), and the invoker composition lives in the sibling
:mod:`lumen_api.toolbelt.wiring`, which this module does NOT import.
"""

