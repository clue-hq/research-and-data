/**
 * Mechanical scene delta emitted by the engine: per-entity replacements
 * computed by pure before/after comparison in Rust. `null` removes an
 * entry; `export_profiles` replaces the whole array when it changed.
 */
export interface SceneDelta {
  meta?: DocumentMeta;
  pages?: Record<PageId, Page | null>;
  nodes?: Record<NodeId, Node | null>;
  slots?: Record<SlotId, Slot | null>;
  assets?: Record<AssetId, AssetRecord | null>;
  export_profiles?: ExportProfile[];
}

export interface Derivation {
  context_key: string | null;
  input_revision: number;
  status: "ready" | "pending" | "unavailable" | "invalid";
  diagnostics: Diagnostic[];
}

export interface EngineApplyOutcome {
  accepted: boolean;
  scene: Scene;
  presentationScene?: Scene;
  derivation?: Derivation;
  message?: string;
  code?: string;
  diagnostics: Diagnostic[];
  inverseOperations: Operation[] | null;
  appliedOperations: number;
}

export interface EngineEditMetadata {
  kind: string;
  touched_targets: unknown[];
  intent: string | null;
  checkpoint_label: string | null;
  inverse_operations: Operation[] | null;
  lineage: unknown | null;
}

export interface EngineStructuredEditOutcome extends EngineApplyOutcome {
  operations: Operation[];
  edit: EngineEditMetadata | null;
}

/**
 * The optimistic engine port EditorApp consumes. `WasmEngine` is the only
 * production implementation since W4 retired the legacy local TS adapter;
 * tests may inject fakes (the `local` kind is reserved for those — local
 * fakes are never enqueued to the server).
 */
export interface OptimisticEnginePort {
  readonly kind: "wasm" | "local";
  readonly scene: Scene;
  readonly version: EngineVersionInfo | null;
  /** Replace local state (reconcile and undo/redo frames). */
  reset(scene: Scene): void;
  applyOperations(operations: Operation[]): EngineApplyOutcome;
  applyStructuredEdit?(edit: StructuredEdit): EngineStructuredEditOutcome;
  /** Wave 3 C3a: point→node hit-test in absolute page space. Optional so
   * test fakes need not implement it; the CanvasKit gesture layer requires
   * a real (wasm) engine. */
  hitTest?(pageId: PageId, x: number, y: number): HitResult;
  /** Wave 3 C4: install editor-measured SkParagraph metrics and relayout.
   * Optional (test fakes need not implement it). */
  setMeasurements?(measurements: TextMeasurement[]): void;
}

/** Immutable, structurally shared merge of an engine delta into a scene. */
export function applySceneDelta(scene: Scene, delta: SceneDelta): Scene {
  const next: Scene = { ...scene };
  if (delta.meta) {
    next.meta = delta.meta;
  }
  if (delta.pages) {
    next.pages = mergeEntityMap(scene.pages, delta.pages);
  }
  if (delta.nodes) {
    next.nodes = mergeEntityMap(scene.nodes, delta.nodes);
  }
  if (delta.slots) {
    next.slots = mergeEntityMap(scene.slots, delta.slots);
  }
  if (delta.assets) {
    next.assets = mergeEntityMap(scene.assets ?? {}, delta.assets);
  }
  if (delta.export_profiles) {
    next.export_profiles = delta.export_profiles;
  }
  return next;
}

function mergeEntityMap<T>(
  current: Record<string, T>,
  changes: Record<string, T | null>
): Record<string, T> {
  const next: Record<string, T> = { ...current };
  for (const [key, value] of Object.entries(changes)) {
    if (value === null) {
      delete next[key];
    } else {
      next[key] = value;
    }
  }
  return next;
}

export class WasmEngine implements OptimisticEnginePort {
  readonly kind = "wasm" as const;
  readonly version: EngineVersionInfo;
  private readonly instance: WasmEngineInstance;
  private snapshot: Scene;
  private presentationSnapshot: Scene;
  derivation: Derivation = { context_key: null, input_revision: 0, status: "ready", diagnostics: [] };

  constructor(module: WasmModule, initialScene: Scene) {
    this.instance = new module.LumenEngine(JSON.stringify(initialScene));
    // The engine relays out on load to establish a coherent whole-tree
    // computed baseline; the render snapshot must be that relaid scene, not
    // the raw input — otherwise the editor renders a scene whose computed
    // geometry disagrees with the engine's (the coordinate-model desync).
    this.snapshot = JSON.parse(this.instance.sceneJson()) as Scene;
    this.presentationSnapshot = this.snapshot;
    this.readPresentation();
    this.version = JSON.parse(module.engineVersion()) as EngineVersionInfo;
  }

  get scene(): Scene {
    return this.snapshot;
  }

  /** Resolved read-only input for paint, measurement and effective inspector reads. */
  get presentationScene(): Scene { return this.presentationSnapshot; }

  private readPresentation(): void {
    if (!this.instance.presentationJson) { this.presentationSnapshot = this.snapshot; return; }
    const { scene, ...derivation } = JSON.parse(this.instance.presentationJson()) as Derivation & { scene: Scene };
    this.presentationSnapshot = scene;
    this.derivation = derivation;
  }

  setRenderContext(context: RenderContext | null): void {
    if (!this.instance.setRenderContext) {
      this.derivation = { context_key: null, input_revision: this.derivation.input_revision + 1,
        status: "unavailable", diagnostics: [{ severity: "error", phase: "brand",
          code: "EDITOR_RENDER_CONTEXT_UNSUPPORTED", message: "Browser engine must be rebuilt for canonical render context.",
          subject: { kind: "document" }, hint: null }] };
      return;
    }
    this.instance.setRenderContext(JSON.stringify(context));
    this.snapshot = JSON.parse(this.instance.sceneJson()) as Scene;
    this.readPresentation();
  }

  private mergePresentation(result: { presentation_delta?: SceneDelta; derivation?: Derivation }): void {
    if (result.derivation) {
      this.presentationSnapshot = applySceneDelta(this.presentationSnapshot, result.presentation_delta ?? {});
      this.derivation = result.derivation;
    } else { this.presentationSnapshot = this.snapshot; }
  }

  reset(scene: Scene): void {
    this.instance.loadScene(JSON.stringify(scene));
    // Render the engine's relaid scene (single-source local heuristic
    // geometry), so reconcile and undo/redo frames never render the
    // server's Skia computed directly — which would jump text on every
    // reconcile. Geometry stays coherent and jump-free across the session.
    this.snapshot = JSON.parse(this.instance.sceneJson()) as Scene;
    this.readPresentation();
  }

  /**
   * Point→node hit-test in absolute page space (scene units). Returns the
   * topmost node and the bottom-to-top stack under the point. Pure read; does
   * not touch the scene. Consumed by the CanvasKit gesture layer (C3b).
   */
  hitTest(pageId: PageId, x: number, y: number): HitResult {
    return JSON.parse(this.instance.hitTest(pageId, x, y)) as HitResult;
  }

  /**
   * Install editor-measured SkParagraph text metrics and relayout, so text
   * `computed` becomes Skia-faithful (Wave 3 C4). An empty array clears the
   * override (back to the heuristic). The relaid scene is adopted as the
   * render snapshot.
   */
  setMeasurements(measurements: TextMeasurement[], expectedRevision = this.derivation.input_revision): TextMeasurementInput[] {
    if (expectedRevision !== this.derivation.input_revision) throw new Error("Stale presentation measurement rejected");
    const ack = JSON.parse(this.instance.setMeasurements(JSON.stringify(measurements))) as {
      ok: boolean;
      missing?: TextMeasurementInput[];
      error?: { message: string };
    };
    if (!ack.ok) throw new Error(ack.error?.message ?? "Text measurements were rejected");
    this.snapshot = JSON.parse(this.instance.sceneJson()) as Scene;
    this.readPresentation();
    return ack.missing ?? [];
  }

  /**
   * Full snapshot straight from engine memory. Reserved for reconcile
   * checks and debugging; the editing path consumes deltas only.
   */
  sceneJson(): string {
    return this.instance.sceneJson();
  }

  applyOperations(operations: Operation[]): EngineApplyOutcome {
    const result = JSON.parse(this.instance.applyOperations(JSON.stringify(operations))) as {
      ok: boolean;
      applied_operations?: number;
      diagnostics?: Diagnostic[];
      inverse_operations?: Operation[] | null;
      delta?: SceneDelta;
      presentation_delta?: SceneDelta;
      derivation?: Derivation;
      error?: { code: string; message: string };
    };
    if (!result.ok) {
      return {
        accepted: false,
        scene: this.snapshot,
        presentationScene: this.presentationSnapshot,
        derivation: this.derivation,
        message: result.error?.message ?? "operation batch rejected by the engine",
        code: result.error?.code,
        diagnostics: result.diagnostics ?? [],
        inverseOperations: null,
        appliedOperations: 0
      };
    }
    this.snapshot = applySceneDelta(this.snapshot, result.delta ?? {});
    this.mergePresentation(result);
    return {
      accepted: true,
      scene: this.snapshot,
      presentationScene: this.presentationSnapshot,
      derivation: this.derivation,
      diagnostics: result.diagnostics ?? [],
      inverseOperations: result.inverse_operations ?? null,
      appliedOperations: result.applied_operations ?? 0
    };
  }

  applyStructuredEdit(edit: StructuredEdit): EngineStructuredEditOutcome {
    const result = JSON.parse(this.instance.applyStructuredEdit(JSON.stringify(edit))) as {
      ok: boolean;
      applied_operations?: number;
      diagnostics?: Diagnostic[];
      operations?: Operation[];
      edit?: EngineEditMetadata;
      delta?: SceneDelta;
      presentation_delta?: SceneDelta;
      derivation?: Derivation;
      error?: { code: string; message: string };
    };
    if (!result.ok) {
      return {
        accepted: false,
        scene: this.snapshot,
        presentationScene: this.presentationSnapshot,
        derivation: this.derivation,
        message: result.error?.message ?? "structured edit rejected by the engine",
        code: result.error?.code,
        diagnostics: result.diagnostics ?? [],
        inverseOperations: null,
        appliedOperations: 0,
        operations: [],
        edit: null
      };
    }
    this.snapshot = applySceneDelta(this.snapshot, result.delta ?? {});
    this.mergePresentation(result);
    return {
      accepted: true,
      scene: this.snapshot,
      presentationScene: this.presentationSnapshot,
      derivation: this.derivation,
      diagnostics: result.diagnostics ?? [],
      inverseOperations: result.edit?.inverse_operations ?? null,
      appliedOperations: result.applied_operations ?? 0,
      operations: result.operations ?? [],
      edit: result.edit ?? null
    };
  }
}

export interface WasmModuleLoadOptions {
  /** Base URL the wasm-pack artifacts are served from. */
  baseUrl?: string;
}

/**
 * Runtime loader for the wasm-pack output in `public/vendor/wasm/`. The Next.js
 * build never depends on the artifact existing: a missing or failing
 * module resolves to `null` and the editor degrades to server-only mode.
 */
export async function loadWasmModule(
  options: WasmModuleLoadOptions = {}
): Promise<WasmModule | null> {
  const baseUrl = options.baseUrl ?? "/vendor/wasm";
  try {
    const moduleUrl = `${baseUrl}/lumen_wasm.js`;
    const module = (await import(/* webpackIgnore: true */ moduleUrl)) as WasmModule & {
      default: (input?: unknown) => Promise<unknown>;
    };
    await module.default({ module_or_path: `${baseUrl}/lumen_wasm_bg.wasm` });
    return module;
  } catch {
    return null;
  }
}

/** W5 version handshake outcome. */
export type WasmCoreActivation =
  | { status: "active"; module: WasmModule }
  | {
      status: "unavailable";
      reason: "load_failed" | "handshake_failed" | "version_mismatch";
      detail: string;
    };

export interface WasmCoreActivationOptions {
  /** Required: the design API origin the handshake verifies against. There is
   * no ambient default — the caller owns configuration. */
  apiBaseUrl: string;
  fetchImpl?: typeof fetch;
  /** Base URL the wasm-pack artifacts are served from. */
  wasmBaseUrl?: string;
  /** Test seam: replaces the runtime module loader. */
  moduleLoader?: () => Promise<WasmModule | null>;
}

/**
 * Load the module AND verify the version handshake against the API's
 * /build-info (Decision E4): the module's `{ schema_version,
 * engine_commit }` must equal the server's exactly. Any failure — module
 * missing, API unreachable, mismatch — leaves the editor in server-only
 * mode. There is never mixed-version optimistic editing, and an
 * unverifiable version counts as a mismatch.
 */
export async function activateWasmCore(
  options: WasmCoreActivationOptions
): Promise<WasmCoreActivation> {
  const loadModule =
    options.moduleLoader ?? (() => loadWasmModule({ baseUrl: options.wasmBaseUrl }));
  // Workspace auth is the BFF's job — defaults to the receiver-safe wrapper;
  // callers inject designBffConfig()'s transport.
  const fetchImpl = options.fetchImpl ?? defaultDesignFetch;
  const apiBaseUrl = options.apiBaseUrl;

  const module = await loadModule();
  if (!module) {
    return {
      status: "unavailable",
      reason: "load_failed",
      detail: "the WASM module could not be loaded from /vendor/wasm/"
    };
  }

  let moduleVersion: EngineVersionInfo;
  try {
    moduleVersion = JSON.parse(module.engineVersion()) as EngineVersionInfo;
  } catch (error) {
    return {
      status: "unavailable",
      reason: "load_failed",
      detail: `the WASM module did not report a version: ${String(error)}`
    };
  }

  try {
    const response = await fetchImpl(`${apiBaseUrl}/build-info`);
    if (!response.ok) {
      return {
        status: "unavailable",
        reason: "handshake_failed",
        detail: `the API build-info request failed (${response.status})`
      };
    }
    const payload = (await response.json()) as {
      build_info?: { schema_version?: number; engine_commit?: string };
    };
    const server = payload.build_info;
    if (
      !server ||
      server.schema_version !== moduleVersion.schema_version ||
      !server.engine_commit ||
      server.engine_commit !== moduleVersion.engine_commit
    ) {
      return {
        status: "unavailable",
        reason: "version_mismatch",
        detail: `editor engine ${moduleVersion.engine_commit} (schema ${moduleVersion.schema_version}) vs API engine ${server?.engine_commit ?? "unknown"} (schema ${server?.schema_version ?? "unknown"})`
      };
    }
  } catch (error) {
    return {
      status: "unavailable",
      reason: "handshake_failed",
      detail: `the API build-info request failed: ${error instanceof Error ? error.message : String(error)}`
    };
  }

  return { status: "active", module };
}
