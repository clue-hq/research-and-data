/**
 * ONE-SHOT, used once at D4 (2026-09-09). NOT part of `npm run build`.
 *
 * The D4 port replaced this package's `generated/tokens.css` with the
 * production design system's. That new file does not define every variable the
 * old one did, and the features that have not yet been re-lifted from the dummy
 * frontend still read the old names. This script diffs the two files' defined
 * sets and writes the old-only definitions to `generated/legacy-compat.css`,
 * which the app imports immediately after `tokens.css`.
 *
 * Kept in the tree so the extraction is reproducible and reviewable, not because
 * it should ever run again. The CSS re-sync job deletes both it and its output.
 *
 * Usage:
 *   node scripts/extract-legacy-compat.mjs <old-tokens.css> <new-tokens.css>
 *
 * Both inputs are single-`:root`-block files, so the output is one `:root`
 * block. If a future input ever carries `[data-theme="…"]` or `@media` contexts
 * this script refuses rather than silently flattening them.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const PACKAGE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.join(PACKAGE_ROOT, "generated", "legacy-compat.css");

const HEADER = `/*
 * Legacy-compat token layer — D4 (2026-09-09).
 * Variables only the pre-D4 design system defined, kept so the not-yet-re-synced
 * features keep rendering. Removed by the CSS re-sync job.
 * Never add to this file.
 *
 * Generated by scripts/extract-legacy-compat.mjs (a one-shot, not the build).
 */
`;

/**
 * Declarations in a flat single-`:root` token file, in source order.
 * Refuses anything with a second selector or an at-rule, since the caller's
 * contract is that the context is reproduced faithfully and this only knows how
 * to reproduce `:root`.
 */
function parseRootDeclarations(file) {
  const text = fs.readFileSync(file, "utf8");
  const withoutComments = text.replace(/\/\*[\s\S]*?\*\//g, "");
  const atRule = withoutComments.match(/@[a-z-]+/i);
  if (atRule) {
    throw new Error(`${file} contains ${atRule[0]}; this one-shot only handles a flat :root block`);
  }
  const selectors = [...withoutComments.matchAll(/([^{}]*)\{/g)].map((m) => m[1].trim());
  const unexpected = selectors.filter((selector) => selector !== ":root");
  if (unexpected.length > 0) {
    throw new Error(`${file} has non-:root selector(s): ${unexpected.join(", ")}`);
  }
  const declarations = [];
  for (const match of withoutComments.matchAll(/(--clue-[a-z0-9-]+)\s*:\s*([^;]+);/g)) {
    declarations.push({ name: match[1], value: match[2].trim() });
  }
  return declarations;
}

const [oldFile, newFile] = process.argv.slice(2);
if (!oldFile || !newFile) {
  throw new Error("usage: node scripts/extract-legacy-compat.mjs <old-tokens.css> <new-tokens.css>");
}

const oldDeclarations = parseRootDeclarations(oldFile);
const newNames = new Set(parseRootDeclarations(newFile).map((d) => d.name));
const legacy = oldDeclarations.filter((d) => !newNames.has(d.name));

const body = legacy.map((d) => `  ${d.name}: ${d.value};`).join("\n");
fs.writeFileSync(OUTPUT, `${HEADER}\n:root {\n${body}\n}\n`, "utf8");

const dangling = legacy.flatMap(({ name, value }) =>
  [...value.matchAll(/var\(\s*(--clue-[a-z0-9-]+)\s*[,)]/g)]
    .map((m) => m[1])
    .filter((referenced) => !newNames.has(referenced) && !legacy.some((d) => d.name === referenced))
    .map((referenced) => `${name} -> ${referenced}`),
);

console.log(`old: ${oldDeclarations.length}  new: ${newNames.size}  legacy-only: ${legacy.length}`);
console.log(`wrote ${path.relative(PACKAGE_ROOT, OUTPUT)}`);
if (dangling.length > 0) {
  console.log(`WARNING: legacy values referencing an undefined variable:\n  ${dangling.join("\n  ")}`);
}
